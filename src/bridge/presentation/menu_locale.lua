local function source(value, ...)
    if select("#", ...) == 0 then
        return value
    end
    return string.format(value, ...)
end
local function translate(value, ...)
    return source(english[value] or value, ...)
end
local function chinese(value, ...)
    return source(chineseErrors[value] or value, ...)
end
return function(nativeLobby, language)
    if nativeLobby then
        return source
    end
    return language == "zh" and chinese or translate
end
