inline constexpr std::uint32_t available = 1u << 24;
inline std::uint32_t preview(unsigned character, const lan::Progress& progress) {
    if (character >= counters.size())
        return 0;
    std::uint32_t result = available;
    for (unsigned layer = 0; layer < counters[character].size(); ++layer)
        result |= std::min(2u, progress.counters[counters[character][layer]] & 3u) << (2 * layer);
    return result;
}
inline std::optional<std::array<std::uint8_t, 12>> layers(std::uint32_t preview) {
    if (!(preview & available) || (preview & ~(available | (available - 1))))
        return {};
    std::array<std::uint8_t, 12> result;
    for (unsigned i = 0; i < result.size(); ++i) {
        result[i] = (preview >> (2 * i)) & 3;
        if (result[i] > 2)
            return {};
    }
    return result;
}
